-- DESAFIO: PROJETO LOGICO DE BANCO DE DADOS - E-COMMERCE
-- SGBD: PostgreSQL 18 (compativel com versoes recentes do PostgreSQL)
-- ATENCAO: este arquivo APAGA o schema ecommerce e recria as tabelas.
-- Execute no banco de dados de estudo, nunca em ambiente de producao.

BEGIN;
DROP SCHEMA IF EXISTS ecommerce CASCADE;
CREATE SCHEMA ecommerce;
SET search_path TO ecommerce, public;

-- Superclasse: dados comuns a todos os clientes.
CREATE TABLE cliente (
    id_cliente BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(120) NOT NULL,
    email VARCHAR(150) NOT NULL UNIQUE,
    telefone VARCHAR(20),
    tipo_cliente CHAR(2) NOT NULL CHECK (tipo_cliente IN ('PF', 'PJ')),
    UNIQUE (id_cliente, tipo_cliente)
);

-- Subclasse PF: a PK e tambem FK para cliente.
CREATE TABLE cliente_pf (
    id_cliente BIGINT PRIMARY KEY
        REFERENCES cliente(id_cliente) ON DELETE CASCADE,
    cpf CHAR(11) NOT NULL UNIQUE CHECK (cpf ~ '^[0-9]{11}$'),
    data_nascimento DATE
);

-- Subclasse PJ: a PK e tambem FK para cliente.
CREATE TABLE cliente_pj (
    id_cliente BIGINT PRIMARY KEY
        REFERENCES cliente(id_cliente) ON DELETE CASCADE,
    cnpj CHAR(14) NOT NULL UNIQUE CHECK (cnpj ~ '^[0-9]{14}$'),
    razao_social VARCHAR(150) NOT NULL,
    nome_fantasia VARCHAR(150)
);

CREATE TABLE produto (
    id_produto BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(120) NOT NULL,
    descricao TEXT,
    preco NUMERIC(12,2) NOT NULL CHECK (preco > 0),
    categoria VARCHAR(80) NOT NULL
);

CREATE TABLE pedido (
    id_pedido BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_cliente BIGINT NOT NULL REFERENCES cliente(id_cliente),
    data_pedido DATE NOT NULL DEFAULT CURRENT_DATE,
    status_pedido VARCHAR(20) NOT NULL DEFAULT 'PENDENTE'
        CHECK (status_pedido IN ('PENDENTE', 'PAGO', 'ENVIADO', 'ENTREGUE', 'CANCELADO')),
    valor_total NUMERIC(12,2) NOT NULL CHECK (valor_total >= 0),
    UNIQUE (id_pedido, id_cliente)
);

-- Relacionamento N:N entre pedido e produto.
CREATE TABLE item_pedido (
    id_pedido BIGINT NOT NULL REFERENCES pedido(id_pedido),
    id_produto BIGINT NOT NULL REFERENCES produto(id_produto),
    quantidade INTEGER NOT NULL CHECK (quantidade > 0),
    preco_unitario NUMERIC(12,2) NOT NULL CHECK (preco_unitario >= 0),
    PRIMARY KEY (id_pedido, id_produto)
);

-- Um cliente pode cadastrar varias formas de pagamento.
CREATE TABLE forma_pagamento (
    id_forma_pagamento BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_cliente BIGINT NOT NULL REFERENCES cliente(id_cliente),
    tipo VARCHAR(20) NOT NULL
        CHECK (tipo IN ('CARTAO', 'PIX', 'BOLETO')),
    identificador_mascarado VARCHAR(80),
    token_referencia VARCHAR(100),
    UNIQUE (id_forma_pagamento, id_cliente)
);

-- O id_cliente aparece nas duas FKs compostas para impedir que um
-- pagamento use uma forma cadastrada por cliente diferente do dono do pedido.
CREATE TABLE pagamento (
    id_pagamento BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_cliente BIGINT NOT NULL,
    id_pedido BIGINT NOT NULL,
    id_forma_pagamento BIGINT NOT NULL,
    valor NUMERIC(12,2) NOT NULL CHECK (valor > 0),
    data_pagamento DATE,
    status_pagamento VARCHAR(20) NOT NULL DEFAULT 'PENDENTE'
        CHECK (status_pagamento IN ('PENDENTE', 'PAGO', 'ESTORNADO')),
    FOREIGN KEY (id_pedido, id_cliente)
        REFERENCES pedido(id_pedido, id_cliente),
    FOREIGN KEY (id_forma_pagamento, id_cliente)
        REFERENCES forma_pagamento(id_forma_pagamento, id_cliente)
);

-- Um pedido possui, no maximo, uma entrega.
CREATE TABLE entrega (
    id_entrega BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_pedido BIGINT NOT NULL UNIQUE REFERENCES pedido(id_pedido),
    status_entrega VARCHAR(20) NOT NULL
        CHECK (status_entrega IN ('PREPARANDO', 'EM_TRANSITO', 'ENTREGUE', 'ATRASADO')),
    codigo_rastreio VARCHAR(60) UNIQUE,
    transportadora VARCHAR(100),
    data_envio DATE,
    data_prevista DATE,
    data_entrega DATE,
    CONSTRAINT ck_entrega_data CHECK (
        (status_entrega = 'ENTREGUE' AND data_entrega IS NOT NULL)
        OR (status_entrega <> 'ENTREGUE' AND data_entrega IS NULL)
    ),
    CONSTRAINT ck_entrega_envio CHECK (
        data_entrega IS NULL OR data_envio IS NOT NULL
    )
);

CREATE TABLE fornecedor (
    id_fornecedor BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    razao_social VARCHAR(150) NOT NULL,
    cnpj CHAR(14) NOT NULL UNIQUE CHECK (cnpj ~ '^[0-9]{14}$')
);

CREATE TABLE vendedor_terceiro (
    id_vendedor BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(150) NOT NULL,
    documento VARCHAR(14) NOT NULL UNIQUE
        CHECK (documento ~ '^([0-9]{11}|[0-9]{14})$')
);

CREATE TABLE estoque (
    id_estoque BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    localizacao VARCHAR(120) NOT NULL
);

-- Mapeamento das associacoes muitos-para-muitos do modelo EER.
CREATE TABLE produto_fornecedor (
    id_produto BIGINT NOT NULL REFERENCES produto(id_produto),
    id_fornecedor BIGINT NOT NULL REFERENCES fornecedor(id_fornecedor),
    PRIMARY KEY (id_produto, id_fornecedor)
);

CREATE TABLE produto_vendedor (
    id_produto BIGINT NOT NULL REFERENCES produto(id_produto),
    id_vendedor BIGINT NOT NULL REFERENCES vendedor_terceiro(id_vendedor),
    PRIMARY KEY (id_produto, id_vendedor)
);

CREATE TABLE produto_estoque (
    id_produto BIGINT NOT NULL REFERENCES produto(id_produto),
    id_estoque BIGINT NOT NULL REFERENCES estoque(id_estoque),
    quantidade INTEGER NOT NULL CHECK (quantidade >= 0),
    PRIMARY KEY (id_produto, id_estoque)
);

-- Garantia da especializacao TOTAL E EXCLUSIVA:
-- ao concluir a transacao, cada CLIENTE deve aparecer EXATAMENTE
-- em uma das subclasses, compativel com seu tipo ('PF' ou 'PJ').
-- Constraint triggers sao adiadas ate o COMMIT para permitir inserir
-- a superclasse e sua subclasse na mesma transacao.
CREATE OR REPLACE FUNCTION ecommerce.validar_especializacao_cliente()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
    v_id BIGINT;
    v_tipo CHAR(2);
    v_possui_pf BOOLEAN;
    v_possui_pj BOOLEAN;
BEGIN
    IF TG_OP = 'DELETE' THEN
        v_id := OLD.id_cliente;
    ELSE
        v_id := NEW.id_cliente;
    END IF;

    SELECT tipo_cliente INTO v_tipo
    FROM ecommerce.cliente
    WHERE id_cliente = v_id;

    -- Se o cliente foi apagado, nao ha especializacao a validar.
    IF NOT FOUND THEN
        RETURN NULL;
    END IF;

    SELECT EXISTS (
        SELECT 1 FROM ecommerce.cliente_pf WHERE id_cliente = v_id
    ) INTO v_possui_pf;
    SELECT EXISTS (
        SELECT 1 FROM ecommerce.cliente_pj WHERE id_cliente = v_id
    ) INTO v_possui_pj;

    IF (v_tipo = 'PF' AND v_possui_pf AND NOT v_possui_pj)
       OR (v_tipo = 'PJ' AND v_possui_pj AND NOT v_possui_pf) THEN
        RETURN NULL;
    END IF;

    RAISE EXCEPTION
        'Cliente % deve pertencer exclusivamente a subclasse %',
        v_id, v_tipo;
END;
$$;

CREATE CONSTRAINT TRIGGER conferir_cliente
AFTER INSERT OR UPDATE ON cliente
DEFERRABLE INITIALLY DEFERRED
FOR EACH ROW EXECUTE FUNCTION ecommerce.validar_especializacao_cliente();

CREATE CONSTRAINT TRIGGER conferir_cliente_pf
AFTER INSERT OR UPDATE OR DELETE ON cliente_pf
DEFERRABLE INITIALLY DEFERRED
FOR EACH ROW EXECUTE FUNCTION ecommerce.validar_especializacao_cliente();

CREATE CONSTRAINT TRIGGER conferir_cliente_pj
AFTER INSERT OR UPDATE OR DELETE ON cliente_pj
DEFERRABLE INITIALLY DEFERRED
FOR EACH ROW EXECUTE FUNCTION ecommerce.validar_especializacao_cliente();

COMMIT;
